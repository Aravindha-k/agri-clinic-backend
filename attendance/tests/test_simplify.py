"""Simplified admin contract: name+area shops, name+shop employees, transfer."""

from __future__ import annotations

import datetime

from django.contrib.auth import get_user_model
from rest_framework.test import APIClient, APITestCase

from attendance.models import (
    AttendanceAuditLog,
    AttendanceEmployee,
    EmployeeShopAssignment,
    Shift,
    Shop,
)
from attendance.services import create_shop
from attendance.tests.helpers import (
    make_admin,
    make_employee,
    make_field_user,
    make_shop,
)

User = get_user_model()

SHOPS_URL = "/api/v1/admin/attendance/shops/"
EMPLOYEES_URL = "/api/v1/admin/attendance/employees/"


class _AdminTestCase(APITestCase):
    def setUp(self):
        self.admin = make_admin()
        self.client = APIClient()
        self.client.force_authenticate(user=self.admin)


class ShopSimplifyTests(_AdminTestCase):
    def test_create_shop_with_only_name_and_area(self):
        resp = self.client.post(
            SHOPS_URL, {"name": "Kavya Main", "area": "Old Market"},
            format="json",
        )
        self.assertEqual(resp.status_code, 201, resp.content)
        data = resp.json()
        self.assertTrue(data["code"].startswith("SHOP-"))
        self.assertEqual(data["area"], "Old Market")
        shop = Shop.objects.get(pk=data["id"])
        self.assertEqual(shop.name, "Kavya Main")
        self.assertEqual(shop.area, "Old Market")

    def test_area_stored_and_returned(self):
        shop = make_shop(area="Station Road")
        resp = self.client.get(f"{SHOPS_URL}{shop.id}/")
        self.assertEqual(resp.json()["area"], "Station Road")

    def test_explicit_code_still_accepted(self):
        resp = self.client.post(
            SHOPS_URL,
            {"name": "Legacy", "code": "SHOP-CUSTOM", "area": "A"},
            format="json",
        )
        self.assertEqual(resp.status_code, 201, resp.content)
        self.assertEqual(resp.json()["code"], "SHOP-CUSTOM")

    def test_name_required(self):
        resp = self.client.post(SHOPS_URL, {"area": "X"}, format="json")
        self.assertEqual(resp.status_code, 400)

    def test_autogenerated_codes_are_unique_and_sequential(self):
        a = create_shop(name="A")
        b = create_shop(name="B")
        self.assertNotEqual(a.code, b.code)
        self.assertEqual(
            int(a.code.split("-")[-1]) + 1, int(b.code.split("-")[-1])
        )

    def test_autogenerated_code_never_collides_with_existing(self):
        make_shop(code="SHOP-0009")
        c = create_shop(name="C")
        self.assertEqual(c.code, "SHOP-0010")

    def test_no_gps_or_geofence_required(self):
        resp = self.client.post(SHOPS_URL, {"name": "S", "area": "Z"},
                                format="json")
        self.assertEqual(resp.status_code, 201)
        self.assertIsNone(resp.json()["latitude"])


class EmployeeSimplifyTests(_AdminTestCase):
    def setUp(self):
        super().setUp()
        self.shop = make_shop()

    def test_create_employee_with_only_name_and_shop(self):
        resp = self.client.post(
            EMPLOYEES_URL,
            {"full_name": "Ravi Kumar", "shop": self.shop.id},
            format="json",
        )
        self.assertEqual(resp.status_code, 201, resp.content)
        data = resp.json()["data"]
        self.assertTrue(data["employee_code"].startswith("EMP-"))
        self.assertEqual(data["shop_id"], self.shop.id)
        self.assertEqual(data["shop_code"], self.shop.code)
        emp = AttendanceEmployee.objects.get(pk=data["id"])
        self.assertIsNone(emp.linked_profile)
        asg = EmployeeShopAssignment.objects.get(employee=emp)
        self.assertEqual(asg.shop, self.shop)
        self.assertTrue(asg.is_active)

    def test_create_employee_without_shop_allowed(self):
        resp = self.client.post(EMPLOYEES_URL, {"full_name": "No Shop Yet"},
                                format="json")
        self.assertEqual(resp.status_code, 201, resp.content)
        self.assertIsNone(resp.json()["data"]["shop_id"])

    def test_inactive_shop_rejected_atomically(self):
        inactive = make_shop(code="SHOP-INACT", is_active=False)
        resp = self.client.post(
            EMPLOYEES_URL,
            {"full_name": "Should Fail", "shop": inactive.id},
            format="json",
        )
        self.assertEqual(resp.status_code, 400)
        self.assertFalse(
            AttendanceEmployee.objects.filter(full_name="Should Fail").exists()
        )
        self.assertFalse(
            EmployeeShopAssignment.objects.filter(shop=inactive).exists()
        )

    def test_phone_not_required(self):
        resp = self.client.post(
            EMPLOYEES_URL, {"full_name": "No Phone", "shop": self.shop.id},
            format="json",
        )
        self.assertEqual(resp.status_code, 201)
        self.assertEqual(resp.json()["data"]["phone"], "")

    def test_explicit_employee_code_still_accepted(self):
        resp = self.client.post(
            EMPLOYEES_URL,
            {"full_name": "Coded", "employee_code": "KAC-EMP-777",
             "shop": self.shop.id},
            format="json",
        )
        self.assertEqual(resp.status_code, 201, resp.content)
        self.assertEqual(resp.json()["data"]["employee_code"], "KAC-EMP-777")

    def test_no_django_user_created(self):
        before = User.objects.count()
        self.client.post(
            EMPLOYEES_URL, {"full_name": "No Login", "shop": self.shop.id},
            format="json",
        )
        self.assertEqual(User.objects.count(), before)


class EmployeeTransferTests(_AdminTestCase):
    def setUp(self):
        super().setUp()
        self.shop_a = make_shop(code="SHOP-A1")
        self.shop_b = make_shop(code="SHOP-B1")
        self.employee = make_employee()
        self.asg = EmployeeShopAssignment.objects.create(
            employee=self.employee, shop=self.shop_a
        )

    def _transfer(self, emp_id, shop_id):
        return self.client.post(
            f"{EMPLOYEES_URL}{emp_id}/transfer/", {"shop_id": shop_id},
            format="json",
        )

    def test_transfer_ends_old_and_creates_new(self):
        resp = self._transfer(self.employee.id, self.shop_b.id)
        self.assertEqual(resp.status_code, 200, resp.content)
        data = resp.json()["data"]
        self.assertEqual(data["employee"]["shop_id"], self.shop_b.id)
        self.asg.refresh_from_db()
        self.assertFalse(self.asg.is_active)
        self.assertIsNotNone(self.asg.valid_to)
        new = EmployeeShopAssignment.objects.get(
            employee=self.employee, shop=self.shop_b
        )
        self.assertTrue(new.is_active)
        self.assertEqual(
            EmployeeShopAssignment.objects.filter(
                employee=self.employee, is_active=True
            ).count(), 1
        )

    def test_transfer_preserves_history(self):
        self._transfer(self.employee.id, self.shop_b.id)
        self.assertEqual(
            EmployeeShopAssignment.objects.filter(
                employee=self.employee
            ).count(), 2
        )

    def test_transfer_back_reactivates_old_row(self):
        self._transfer(self.employee.id, self.shop_b.id)
        self._transfer(self.employee.id, self.shop_a.id)
        self.assertEqual(
            EmployeeShopAssignment.objects.filter(
                employee=self.employee
            ).count(), 2
        )

    def test_transfer_to_inactive_shop_rejected(self):
        inactive = make_shop(code="SHOP-IN", is_active=False)
        resp = self._transfer(self.employee.id, inactive.id)
        self.assertEqual(resp.status_code, 400)
        self.asg.refresh_from_db()
        self.assertTrue(self.asg.is_active)

    def test_transfer_missing_shop_param(self):
        resp = self.client.post(
            f"{EMPLOYEES_URL}{self.employee.id}/transfer/", {}, format="json"
        )
        self.assertEqual(resp.status_code, 400)

    def test_transfer_audit_logged(self):
        self._transfer(self.employee.id, self.shop_b.id)
        self.assertTrue(
            AttendanceAuditLog.objects.filter(
                action="EMPLOYEE_TRANSFERRED"
            ).exists()
        )

    def test_transfer_requires_admin(self):
        resp = APIClient().post(
            f"{EMPLOYEES_URL}{self.employee.id}/transfer/",
            {"shop_id": self.shop_b.id}, format="json",
        )
        self.assertIn(resp.status_code, (401, 403))

    def test_field_officer_cannot_transfer(self):
        field_user, _ = make_field_user()
        c = APIClient()
        c.force_authenticate(user=field_user)
        resp = c.post(
            f"{EMPLOYEES_URL}{self.employee.id}/transfer/",
            {"shop_id": self.shop_b.id}, format="json",
        )
        self.assertIn(resp.status_code, (401, 403))


class ShiftOptionalTests(APITestCase):
    """Attendance must work with no shift configured on the assignment."""

    def test_assignment_without_shift(self):
        emp = make_employee()
        shop = make_shop()
        asg = EmployeeShopAssignment.objects.create(employee=emp, shop=shop)
        self.assertIsNone(asg.shift)

    def test_shift_model_preserved(self):
        shop = make_shop()
        shift = Shift.objects.create(
            shop=shop, name="Morning",
            start_time=datetime.time(9, 0), end_time=datetime.time(17, 0),
        )
        self.assertTrue(shift.pk)
        self.assertTrue(shift.is_active)
